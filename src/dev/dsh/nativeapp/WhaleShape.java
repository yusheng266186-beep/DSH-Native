    private final float[] pose = new float[BASE.length];
    private static float smooth(float value) {
        float t = Math.max(0f, Math.min(1f, value));
        return t * t * (3f - 2f * t);
    }
    void trace(float phase, float closure, boolean animated, Sink sink) {
        double angle = animated ? Math.toRadians(6.5) * Math.sin(phase * Math.PI * 2 - .35) : 0d;
        float cosine = (float) Math.cos(angle), sine = (float) Math.sin(angle);
        float eyeScale = 1f - .9f * Math.max(0f, Math.min(1f, closure));
        int offset = 0, contour = -1;
        for (byte command : COMMANDS) {
            if (command == 0) contour++;
            int count = command == 0 ? 2 : command == 1 ? 6 : 0;
            for (int i = offset; i < offset + count; i += 2) {
                float x = BASE[i], y = BASE[i + 1];
                if (contour == 2) y = 24.6f + (y - 24.6f) * eyeScale;
                // A smooth field across the neck moves adjacent contour points together.
                // No body/tail split, overlapping cut edge, bitmap mesh or per-frame allocations.
                float weight = smooth((x - 28f) / 13f) * smooth((28f - y) / 16f);
                float dx = x - 38.5f, dy = y - 22f;
                pose[i] = x + weight * (dx * (cosine - 1f) - dy * sine);
                pose[i + 1] = y + weight * (dx * sine + dy * (cosine - 1f));
            }
            if (command == 0) sink.move(pose[offset], pose[offset + 1]);
            else if (command == 1) sink.curve(pose[offset], pose[offset + 1], pose[offset + 2], pose[offset + 3], pose[offset + 4], pose[offset + 5]);
            else sink.close();
            offset += count;
        }
    }
